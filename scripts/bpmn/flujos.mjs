// Flujos BPMN de DevHub Técnico, uno por transacción, en 3 carriles:
// Front (Angular en el navegador) · Servicio (API de Supabase: Auth, PostgREST,
// Storage, RPC) · BD (PostgreSQL: RLS, triggers, CHECK).
// Las partes extensas son subprocesos (SPxx) con su propio archivo.
// Al cambiar la app, actualizar aquí y regenerar: npm run bpmn

/** Nodo: n(id, tipo, carril, columna, nombre, fila = 0). */
const n = (id, type, lane, col, name, row = 0) => ({ id, type, lane, col, name, row });
/** Subproceso colapsado que remite a su archivo. */
const sp = (id, lane, col, code, name, row = 0) => ({
  ...n(id, 'subprocess', lane, col, `${code} · ${name}`, row),
  doc: `Detalle en el archivo ${code}.`,
});

